begin;
create table if not exists public.restaurants (
  id bigint generated by default as identity primary key,
  name text not null, category text not null, location text not null,
  price_range text not null default '정보 없음', rating numeric not null default 0,
  description text not null default '', recommended_menu text[] not null default '{}',
  likes integer not null default 0, image text not null default ''
);
-- [이론: 계정과 사용자 ID] Auth 계정과 앱 프로필은 이름·이메일이 아닌 같은 UUID로 연결합니다.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null default '', name text not null, avatar text not null default '',
  provider text not null default 'email', user_type text not null default 'user' check (user_type in ('user','admin')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  constraint foodmap_profile_name check (length(btrim(name)) between 1 and 80)
);
create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  restaurant_name text not null check (length(btrim(restaurant_name)) between 1 and 300),
  category text not null check (length(btrim(category)) between 1 and 300),
  location text not null check (length(btrim(location)) between 1 and 300),
  price_range text not null default '', recommended_menu text[] not null default '{}',
  review text not null default '', submitter_id uuid not null references public.profiles(id),
  submitter_name text not null, submitter_email text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  reviewed_by uuid references public.profiles(id), reviewed_at timestamptz,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
alter table public.restaurants add column if not exists source_submission_id bigint unique references public.submissions(id) on delete set null;
alter table public.restaurants add column if not exists created_at timestamptz not null default now();
alter table public.restaurants add column if not exists updated_at timestamptz not null default now();
alter table public.restaurants add column if not exists created_by uuid references public.profiles(id) on delete set null;
alter table public.restaurants alter column created_by set default auth.uid();
create index if not exists foodmap_restaurants_creator on public.restaurants(created_by);
update public.restaurants as restaurant
set created_by = submission.submitter_id
from public.submissions as submission
where restaurant.source_submission_id = submission.id and restaurant.created_by is null;
do $$ begin
