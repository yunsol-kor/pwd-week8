create schema if not exists foodmap_private;
revoke all on schema foodmap_private from public,anon,authenticated;
grant usage on schema foodmap_private to authenticated;
create or replace function foodmap_private.can_write_restaurant(owner_id uuid, allow_admin boolean)
returns boolean language sql stable security definer set search_path='' as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and is_active
      and (id = owner_id or (allow_admin and user_type = 'admin'))
  );
$$;
revoke all on function foodmap_private.can_write_restaurant(uuid,boolean) from public,anon,authenticated;
grant execute on function foodmap_private.can_write_restaurant(uuid,boolean) to authenticated;

